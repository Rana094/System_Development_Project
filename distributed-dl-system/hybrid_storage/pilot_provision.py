def require_pilot_units_inactive(plan):
    units=('dl-hybrid-node.service',) if plan['role']=='worker' else ('dl-hybrid-controller.service','dl-hybrid-portal.service')
    for unit in units:
        state=systemctl(plan,'show',unit,'--property=ActiveState').stdout.strip()
        if state not in ('ActiveState=inactive','ActiveState=failed'):
            raise PermissionError('Prior pilot service is not inactive: '+unit)


def prepare(plan,source):
    previous=Path(plan['state_base'])/'PREPARED.json'
    if previous.exists():
        if json.loads(previous.read_bytes())!=dict(plan_sha256=digest(encoded(plan)),role=plan['role']):raise PermissionError('Existing prepared release differs')
        verify_payload(plan,Path(plan['code_root']))
        return dict(status='ALREADY_PREPARED_SERVICES_UNCHANGED',host=plan['host'])
    if plan['role']=='worker':
        old=call(['/usr/bin/systemctl','show','dl-node-agent.service','--property=ActiveState,MainPID']).stdout
        if 'ActiveState=inactive' not in old or 'MainPID=0' not in old or not (Path(plan['state_base'])/'LEGACY-SERVICES.json').is_file():
            raise PermissionError('Drain old controller and stop idle legacy worker before provisioning credentials')
    code=install_source(plan,source);python=copy_packages(plan)
    base=directory('/var/lib/dl-hybrid-pilot',mode=0o755);state=directory(base/plan['release'],mode=0o755)
    uid,gid=(0,0) if plan['role']=='worker' else (125,125)
    for name in plan['directories']:directory(state/name,uid,gid)
    for name,value in plan['documents'].items():
        path=state/name;write(path,value);os.chown(path,uid,gid)
    if plan['role']=='worker':
        sys.path.insert(0,str(code/'agent'));sys.path.insert(0,str(code))
        from environment_worker import probe,pip_check
        # Dedicated training environment, never the unsupported live service env.
        testenv=Path(plan['code_root']).parent/'capsule-probe'
        if not testenv.exists():
            call(['/usr/bin/python3','-I','-B','-m','venv','--without-pip',str(testenv)])
            site=testenv/'lib'/('python'+'.'.join(plan['system_python'].split('.')[:2]))/'site-packages'
            # Newly created ordinary empty directory only.
            if any(site.iterdir()):raise ValueError('Unexpected capsule probe content')
            site.rmdir();site.symlink_to(Path(plan['code_root']).parent/'training-site')
        result=probe(testenv/'bin/python');pip_check(testenv/'bin/python')
        call([str(testenv/'bin/python'),'-I','-B','-c','import numpy,torch; assert torch.distributed.is_gloo_available(); assert torch.tensor([1,2]).sum().item()==3'])
        capsule=dict(schema_version=1,site_root=str(Path(plan['code_root']).parent/'training-site'),
            runtime=dict(python=plan['system_python'],machine=platform.machine(),system=platform.system()),packages=result['packages'],
            requirements_sha256=plan['requirements_sha256'],profiles=['isolated','pytorch-cpu'])
        write(state/'worker/worker-storage/capsule.json',capsule)
    else:
        # Copy ONLY portal authentication metadata to the new private owner;
        # existing files are read, never changed or printed.
        for name,sha in plan['portal_files'].items():
            raw=(Path(plan['legacy_root'])/'storage/portal'/name).read_bytes()
            if digest(raw)!=sha:raise ValueError('Portal metadata changed since review')
            target=state/'controller/portal'/name;write(target,raw);os.chown(target,125,125)
        # A subprocess drops identity BEFORE importing any DB module. The
        # initialization targets only the new pilot DB, never the original DB.
        call([str(python),'-I','-B',str(code/'tools/hybrid_pilot_init.py'),str(state/'controller/config-controller.json')],
             user=125,group=125,extra_groups=[])
    if plan['role']=='controller':
        # Exact reviewed commands only; no arbitrary Python, paths, SSH, units
        # or user-controlled arguments are granted to the publisher/operator.
        policy=sudo_policy(plan)
        candidate=state/'sudoers-candidate';write(candidate,policy,0o440)
        call(['/usr/sbin/visudo','-cf',str(candidate)])
        require_pilot_units_inactive(plan)
        install_sudo_policy(plan,policy,state)
    write(state/'plan.json',plan)
    write(state/'PREPARED.json',dict(plan_sha256=digest(encoded(plan)),role=plan['role']))
    return dict(status='PREPARED_SERVICES_UNCHANGED',code_root=str(code),state_root=str(state),packages_offline=True)


def legacy_services(plan):
    return ['dl-node-agent.service'] if plan['role']=='worker' else ['dl-student-portal.service','dl-dispatcher.service']


def systemctl(plan,*args,legacy=False):
    argv=['/usr/bin/systemctl']
    if legacy and plan['role']=='controller':
        argv=['/usr/sbin/runuser','-u',plan['operator_name'],'--','/usr/bin/env',
              f'XDG_RUNTIME_DIR=/run/user/{plan["operator_uid"]}',f'DBUS_SESSION_BUS_ADDRESS=unix:path=/run/user/{plan["operator_uid"]}/bus',
              '/usr/bin/systemctl','--user']
    return call([*argv,*args])


def idle_controller(plan):
    from urllib.parse import quote
    path=Path(plan['legacy_root'])/'controller/jobs.db'
    with sqlite3.connect('file:'+quote(str(path),safe='/')+'?mode=ro',uri=True) as db:
        if db.execute("SELECT 1 FROM jobs WHERE status IN ('SCHEDULED','RUNNING','CANCELLING') LIMIT 1").fetchone():raise PermissionError('Legacy active jobs prevent maintenance')
        if db.execute('SELECT 1 FROM resource_reservations LIMIT 1').fetchone():raise PermissionError('Legacy reservations prevent maintenance')
        if db.execute('SELECT 1 FROM execution_leases WHERE revoked=0 AND expires_at>? LIMIT 1',(time.time(),)).fetchone():raise PermissionError('Legacy unexpired leases prevent maintenance')


def drain(plan):
    if plan['role']!='controller':raise ValueError('Controller admission must be drained first')
    state=Path(plan['state_base'])
    if (state/'DRAINED.json').exists():
        for unit in legacy_services(plan):
            if 'ActiveState=active' in systemctl(plan,'show',unit,'--property=ActiveState',legacy=True).stdout:raise PermissionError('Legacy admission restarted after drain')
        idle_controller(plan);return dict(status='ALREADY_DRAINED')
    idle_controller(plan)
    before={u:systemctl(plan,'show',u,'--property=ActiveState,UnitFileState',legacy=True).stdout for u in legacy_services(plan)}
    write(state/'LEGACY-SERVICES.json',before)
    try:
        # Stop new admissions first, then the old scheduler. No worker process is
        # stopped if a concurrent dispatch raced this final maintenance fence.
        systemctl(plan,'stop','dl-student-portal.service',legacy=True)
        idle_controller(plan)
        systemctl(plan,'stop','dl-dispatcher.service',legacy=True)
        idle_controller(plan)
    except Exception:
        for unit,properties in before.items():
            if 'ActiveState=active' in properties:systemctl(plan,'start',unit,legacy=True)
        raise
    backup=state/'legacy-jobs-snapshot.sqlite'
    if not backup.exists():
        src=sqlite3.connect((Path(plan['legacy_root'])/'controller/jobs.db').as_uri()+'?mode=ro',uri=True)
        dst=sqlite3.connect(backup);src.backup(dst);dst.close();src.close()
        backup.chmod(0o600)
    for unit in legacy_services(plan):systemctl(plan,'disable',unit,legacy=True)
    write(state/'DRAINED.json',dict(at_ns=time.time_ns(),active_jobs=0,reservations=0,live_leases=0))
    return dict(status='LEGACY_ADMISSION_DRAINED_DATA_PRESERVED')


def firewall(config):
    from .linux_boundary import LinuxConfig,nft_policy,policy_digest
    cfg=LinuxConfig(**config['boundary'])
    receipt=Path(cfg.state_root)/'firewall-receipt.json'
    seen=subprocess.run(['/usr/sbin/nft','-j','list','table','inet',cfg.nft_table],capture_output=True,text=True,timeout=10)
    existed=seen.returncode==0
    if existed and cfg.policy_sha256=='0'*64 and not receipt.exists():raise PermissionError('Will not adopt an existing unowned firewall table')
    if not existed:
        # Creating this one missing table is the only boot mutation. Never
        # replace an existing differing policy or flush the host ruleset.
        policy=nft_policy(cfg)
        call(['/usr/sbin/nft','--check','-f','-'],input=policy)
        call(['/usr/sbin/nft','-f','-'],input=policy)
        seen=call(['/usr/sbin/nft','-j','list','table','inet',cfg.nft_table])
    actual=policy_digest(json.loads(seen.stdout),cfg)
    if cfg.policy_sha256!='0'*64 and actual!=cfg.policy_sha256:raise PermissionError('Existing policy differs; no replacement')
    if receipt.exists() and json.loads(receipt.read_bytes())!=dict(policy_sha256=actual):raise PermissionError('Firewall ownership receipt differs')
    write(receipt,dict(policy_sha256=actual))
    return actual


def activate(plan):
    state=Path(plan['state_base']);code=Path(plan['code_root'])
    if not (state/'PREPARED.json').is_file():raise PermissionError('Complete offline preparation required')
    if (state/'ACTIVATED.json').exists():
        names=['dl-hybrid-node.service'] if plan['role']=='worker' else ['dl-hybrid-controller.service','dl-hybrid-portal.service']
        if all('ActiveState=active' in systemctl(plan,'show',u,'--property=ActiveState').stdout for u in names):
            return dict(status='ALREADY_ACTIVATED_ACCEPTANCE_PENDING',host=plan['host'])
        raise PermissionError('Previously activated services are not all active; investigate or roll back')
    if plan['role']=='worker':
        # Controller receipt is checked by the orchestration before this call;
        # worker independently refuses any active training before maintenance.
        old=systemctl(plan,'show','dl-node-agent.service','--property=ActiveState,MainPID').stdout
        if 'ActiveState=inactive' not in old or 'MainPID=0' not in old or not (state/'LEGACY-SERVICES.json').is_file():
            raise PermissionError('Original worker must remain stopped under the reviewed maintenance fence')
        account='dl-train-pilot'
        import grp
        try:
            user=pwd.getpwuid(599)
            if user.pw_name!=account or user.pw_gid!=599:raise PermissionError('Dedicated UID collision')
        except KeyError:
            try:
                if grp.getgrgid(599).gr_name!=account:raise PermissionError('Dedicated GID collision')
            except KeyError:call(['/usr/sbin/groupadd','--system','--gid','599',account])
            call(['/usr/sbin/useradd','--system','--no-create-home','--home-dir','/nonexistent','--shell','/usr/sbin/nologin','--uid','599','--gid','599',account])
        configpath=state/'control/config-worker.json';config=json.loads(configpath.read_bytes())
        # Fail before stopping the old service if policy syntax/ownership is bad.
        from .linux_boundary import LinuxConfig,nft_policy,atomic_json
        call(['/usr/sbin/nft','--check','-f','-'],input=nft_policy(LinuxConfig(**config['boundary'])))
        for unit in legacy_services(plan):systemctl(plan,'disable','--now',unit,legacy=True)
        try:
            config['boundary']['policy_sha256']=firewall(config);atomic_json(configpath,config)
            unit=service_unit(plan,'worker',code.parent/'service/bin/python',configpath)
            require_pilot_units_inactive(plan)
            install_owned_release_file(plan,unit,state,Path('/etc/systemd/system/dl-hybrid-node.service'),0o644,
                lambda raw:_owned_prior_unit(plan,'worker',raw))
            systemctl(plan,'daemon-reload');systemctl(plan,'enable','--now','dl-hybrid-node.service')
        except Exception:
            rollback(plan);raise
    else:
        if not (state/'DRAINED.json').is_file():raise PermissionError('Legacy admission drain required before hybrid activation')
        idle_controller(plan)
        directory('/etc/dl-hybrid-pilot')
