SERVICE_PACKAGES=frozenset('flask werkzeug jinja2 markupsafe itsdangerous blinker click requests urllib3 idna charset-normalizer certifi psutil waitress pip setuptools'.split())


def encoded(value):return (json.dumps(value,sort_keys=True,separators=(',',':'),allow_nan=False)+'\n').encode()
def digest(raw):return hashlib.sha256(raw).hexdigest()


def tree_inventory(root):
    """Pin trusted installed package bytes, excluding generated bytecode only."""
    root=Path(root);items=[];size=0
    for base,dirs,files in os.walk(root,followlinks=False):
        dirs[:]=sorted(d for d in dirs if d!='__pycache__')
        for name in sorted(dirs+files):
            p=Path(base)/name;info=p.lstat();relative=p.relative_to(root).as_posix()
            if name.endswith(('.pyc','.pyo')):continue
            if stat.S_ISLNK(info.st_mode):
                target=os.readlink(p)
                resolved=p.resolve()
                if not resolved.is_relative_to(root.resolve()):raise ValueError('Package symlink escapes its approved tree')
                items.append([relative,'link',target])
            elif stat.S_ISDIR(info.st_mode):items.append([relative,'directory'])
            elif stat.S_ISREG(info.st_mode):
                h=hashlib.sha256()
                with p.open('rb') as stream:
                    for chunk in iter(lambda:stream.read(1024**2),b''):h.update(chunk)
                size+=info.st_size;items.append([relative,'file',info.st_size,h.hexdigest(),bool(info.st_mode&0o111)])
            else:raise ValueError('Special file in approved packages')
    return dict(sha256=digest(encoded(sorted(items))),bytes=size,entries=len(items))


def packages(site):
    import importlib.metadata
    selected=[]
    for d in importlib.metadata.distributions(path=[str(site)]):
        name=d.metadata['Name'].lower().replace('_','-')
        if name not in SERVICE_PACKAGES:continue
        selected.append((name,d.version,sorted({str(Path(p).parts[0]) for p in d.files or ()
            if Path(p).parts and Path(p).parts[0] not in ('..','.') and not str(p).endswith(('.pyc','.pyo'))})))
    if {p[0] for p in selected}!=SERVICE_PACKAGES:raise ValueError('Missing approved service dependency')
    return sorted(selected)


def call(argv,**kw):return subprocess.run(argv,check=True,capture_output=True,text=True,timeout=120,**kw)


def write(path,value,mode=0o600):
    path=Path(path);raw=encoded(value) if not isinstance(value,bytes) else value
    if path.exists():
        if path.is_symlink() or path.read_bytes()!=raw:raise PermissionError('Existing provisioned file differs: '+str(path))
        return
    fd=os.open(path,os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW,mode)
    with os.fdopen(fd,'wb') as f:f.write(raw);f.flush();os.fsync(f.fileno())


def directory(path,uid=0,gid=0,mode=0o700):
    path=Path(path)
    if not path.exists():path.mkdir(mode=mode);os.chown(path,uid,gid)
    info=path.lstat()
    if not stat.S_ISDIR(info.st_mode) or (info.st_uid,info.st_gid,stat.S_IMODE(info.st_mode))!=(uid,gid,mode):
        raise PermissionError('Protected provisioned directory differs: '+str(path))
    return path


def load_plan(path,expected):
    raw=Path(path).read_bytes()
    if digest(raw)!=expected:raise ValueError('Reviewed plan hash differs')
    p=json.loads(raw)
    if (p['schema_version']!=1 or p['role'] not in ('controller','worker') or p['host'] not in ('controller','pi02','pi03')
            or p['hostname']!=socket.gethostname() or not re.fullmatch('pilot-[0-9]{8}-[0-9a-f]{12}',p['release'])
            or p['selected_workers']!=['pi02','pi03'] or p['deferred_workers']!=['pi01']):raise ValueError('Invalid reviewed host scope')
    if (p['role']=='controller')!=(p['host']=='controller'):raise ValueError('Host role differs')
    if platform.python_version()!=p['system_python']:raise ValueError('System Python differs')
    if Path(p['code_root'])!=Path('/opt/dl-hybrid-pilot')/p['release']/'app':raise ValueError('Unexpected installed code root')
    if Path(p['state_base'])!=Path('/var/lib/dl-hybrid-pilot')/p['release']:raise ValueError('Unexpected LOCAL pilot root')
    return p


def verify_payload(plan,source):
    actual={p.relative_to(source).as_posix() for p in source.rglob('*') if p.is_file() or p.is_symlink()}
    if actual!=set(plan['files']):raise ValueError('Payload contains unexpected or missing files')
    for name,sha in plan['files'].items():
        p=Path(name)
        if p.is_absolute() or '..' in p.parts or source.joinpath(p).is_symlink() or digest(source.joinpath(p).read_bytes())!=sha:
            raise ValueError('Payload source differs: '+name)


def install_source(plan,source):
    verify_payload(plan,source)
    base=directory('/opt/dl-hybrid-pilot',mode=0o755)
    release=directory(base/plan['release'],mode=0o755)
    code=directory(release/'app',mode=0o755)
    for name,sha in plan['files'].items():
        path=code/name
        current=code
        for part in Path(name).parts[:-1]:current=directory(current/part,mode=0o755)
        raw=(source/name).read_bytes()
        if digest(raw)!=sha:raise ValueError('Source changed during install')
        write(path,raw,0o644)
    verify_payload(plan,code)
    return code


def copy_packages(plan):
    release=Path(plan['code_root']).parent
    destination=release/'service'
    marker=release/'PACKAGES.json'
    if marker.exists():
        if json.loads(marker.read_bytes())!=plan['package_sources']:raise ValueError('Approved package identity differs')
        return destination/'bin/python'
    # Never repair an interrupted environment in place or remove its evidence.
    if destination.exists():raise PermissionError('Interrupted service environment requires a new reviewed release')
    call(['/usr/bin/python3','-I','-B','-m','venv','--without-pip',str(destination)])
    site=destination/'lib'/('python'+'.'.join(plan['system_python'].split('.')[:2]))/'site-packages'
    source=Path(plan['service_site']);approved=packages(source)
    names=sorted({item for _,_,entries in approved for item in entries})
    for name in names:
        src=source/name;target=site/name
        if src.is_dir():shutil.copytree(src,target,symlinks=True,ignore=shutil.ignore_patterns('__pycache__','*.pyc','*.pyo'))
        elif src.is_file():shutil.copy2(src,target)
    if tree_inventory(site)!=plan['package_sources']['service']:raise ValueError('Offline service package bytes changed')
    if plan['role']=='worker':
        training=release/'training-site'
        shutil.copytree(plan['training_site'],training,symlinks=True,ignore=shutil.ignore_patterns('__pycache__','*.pyc','*.pyo'))
        if tree_inventory(training)!=plan['package_sources']['training']:raise ValueError('Offline training package bytes changed')
        for name in plan['numpy_names']:
            src=source/name;target=training/name
            if src.is_dir():shutil.copytree(src,target,symlinks=True,ignore=shutil.ignore_patterns('__pycache__','*.pyc','*.pyo'))
            else:shutil.copy2(src,target)
        # Exact NumPy source hashes were separately pinned by the review.
        for name in plan['numpy_names']:
            if tree_inventory(training/name)!=plan['package_sources']['numpy'][name]:raise ValueError('Offline NumPy bytes changed')
    for root in [destination,*([release/'training-site'] if plan['role']=='worker' else [])]:
        for base,dirs,files in os.walk(root,followlinks=False):
            os.chown(base,0,0);os.chmod(base,0o755)
            for name in files:
                path=Path(base)/name
                if not path.is_symlink():os.chown(path,0,0);path.chmod(0o755 if path.stat().st_mode&0o111 else 0o644)
    python=destination/'bin/python'
    call([str(python),'-I','-B','-m','pip','check'])
    call([str(python),'-I','-B','-c','import flask,requests,psutil,waitress'])
    write(marker,plan['package_sources'])
    return python


