        bridge=encoded(result_bridge_document(plan))
        install_owned_release_file(plan,bridge,state,Path('/etc/dl-hybrid-pilot/result-bridge.json'),0o600,
            lambda raw:_owned_prior_bridge(plan,raw))
        for role in ('controller','portal'):
            name='dl-hybrid-'+role+'.service'
